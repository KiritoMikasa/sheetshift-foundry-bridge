import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const output=new URL('../private-status-crypto.mjs',import.meta.url);
await build({entryPoints:[new URL('./private-status-crypto.mjs',import.meta.url).pathname],outfile:output.pathname,bundle:true,platform:'browser',format:'esm',target:'es2022',minify:true,legalComments:'inline',banner:{js:'// Generated by frontend/scripts/build-foundry-crypto.mjs; see private-status-crypto.LICENSES.txt.'}});
const licenses=[];
for(const name of ['curves','ciphers','hashes']){
  const root=new URL(`../node_modules/@noble/${name}/`,import.meta.url),pkg=JSON.parse(await readFile(new URL('package.json',root),'utf8'));
  licenses.push(`@noble/${name} ${pkg.version}\n${await readFile(new URL('LICENSE',root),'utf8')}`);
}
await writeFile(new URL('../private-status-crypto.LICENSES.txt',import.meta.url),licenses.join('\n\n'));
